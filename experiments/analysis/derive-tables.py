#!/usr/bin/env python3
"""Derived tables for experiments A, size scaling, D, D-scale and F (Phase 15 work order 4 A5).

Reads committed raw records only and writes reproducible CSV and Markdown tables under
experiments/derived/<name>/ (default --out experiments/derived). Each table directory has
sources.csv (path, sha256, bytes of every file read), and every Markdown file names its sources and
their sha256. Missing data is reported as a gap (gaps.csv and the Markdown), never filled in. The
output holds no generation time, so a rerun on the same inputs writes the same bytes. Percentiles
are nearest rank, as load-tests/exp-d-query-load.py computes them.

Usage: python3 -I experiments/analysis/derive-tables.py [--out experiments/derived]
       python3 -I experiments/analysis/derive-tables.py --self-test
Exit: 0 written (gaps are reported, not errors); 1 a source exists but cannot be parsed; 2 usage.
"""
import argparse
import csv
import glob
import hashlib
import json
import math
import os
import re
import sys
import tempfile
from datetime import datetime, timedelta, timezone

REPO = os.path.realpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
TSV = "docs/agent-runs/phase-14/evidence/window-1/p14-window1-results.tsv"
D_SCALE = "experiments/results/exp-d-scale-v1/20261120T001853Z"


def ts(s):
    """UTC datetime from ISO-8601 with Z or an offset."""
    return datetime.fromisoformat(s.replace("Z", "+00:00")).astimezone(timezone.utc)


def iso(d):
    return d.strftime("%Y-%m-%dT%H:%M:%S.") + f"{d.microsecond // 1000:03d}Z"


def minute_floor(d):
    return d.replace(second=0, microsecond=0)


def pct(xs, p):
    s = sorted(xs)
    return s[max(1, math.ceil(p / 100.0 * len(s))) - 1] if s else ""


class Table:
    """One table directory: rows per CSV, the files read (with sha256), and gaps."""

    def __init__(self, root, name, title):
        self.root, self.dir, self.title = root, os.path.join(root, name), title
        self.sources, self.gaps, self.csvs, self.notes = {}, [], [], []

    def read(self, rel, parse=None):
        path = os.path.join(REPO, rel)
        if not os.path.isfile(path):
            self.gaps.append(f"missing source: {rel}")
            return None
        b = open(path, "rb").read()
        self.sources[rel] = (hashlib.sha256(b).hexdigest(), len(b))
        text = b.decode("utf-8")
        return parse(text) if parse else text

    def add(self, fname, cols, rows, caption):
        self.csvs.append((fname, cols, rows, caption))

    def write(self):
        os.makedirs(self.dir, exist_ok=True)
        md = [f"# {self.title}", "", "Generated by experiments/analysis/derive-tables.py from the sources listed below.", ""]
        md += self.notes + ([""] if self.notes else [])
        for fname, cols, rows, caption in self.csvs:
            with open(os.path.join(self.dir, fname), "w", newline="") as f:
                w = csv.writer(f, lineterminator="\n")
                w.writerow(cols)
                w.writerows([[r.get(c, "") for c in cols] for r in rows])
            md += [f"## {caption} ({fname})", "", "| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
            md += ["| " + " | ".join(str(r.get(c, "")).replace("|", "/") for c in cols) + " |" for r in rows] + [""]
        md += ["## Gaps", ""] + ([f"- {g}" for g in self.gaps] or ["- none"]) + [""]
        md += ["## Sources", "", "| path | sha256 | bytes |", "|---|---|---|"]
        md += [f"| {p} | {s} | {n} |" for p, (s, n) in sorted(self.sources.items())] + [""]
        with open(os.path.join(self.dir, "README.md"), "w") as f:
            f.write("\n".join(md))
        with open(os.path.join(self.dir, "sources.csv"), "w", newline="") as f:
            w = csv.writer(f, lineterminator="\n")
            w.writerow(["path", "sha256", "bytes"])
            w.writerows([[p, s, n] for p, (s, n) in sorted(self.sources.items())])
        with open(os.path.join(self.dir, "gaps.csv"), "w", newline="") as f:
            w = csv.writer(f, lineterminator="\n")
            w.writerow(["gap"])
            w.writerows([[g] for g in self.gaps])
        return self.gaps


def rel_glob(pattern):
    return sorted(os.path.relpath(p, REPO) for p in glob.glob(os.path.join(REPO, pattern)))


# ---- Size scaling (Hadoop runs at 25, 50 and 100 percent; D-13) and experiment A ----

def size_scaling(root):
    t = Table(root, "size-scaling", "Size scaling: EMR pipeline runs at 25, 50 and 100 percent (Phase 14 window 1)")
    tsv = t.read(TSV, lambda s: {r[0]: r for r in csv.reader(s.splitlines(), delimiter="\t") if r})
    hdr = tsv.get("record") if tsv else None
    records = [os.path.basename(p) for p in rel_glob("operations/pipeline-runs/*-fraction*")
               if os.path.isdir(os.path.join(REPO, p)) and re.search(r"-fraction(25|50|100)$", p)]
    rows = []
    for rec in records:
        row = {"record": rec, "fraction": rec.rsplit("fraction", 1)[1]}
        tr = dict(zip(hdr, tsv[rec])) if tsv and hdr and rec in tsv and len(tsv[rec]) == len(hdr) else None
        run = t.read(f"operations/pipeline-runs/{rec}/run.json", json.loads)
        if run is None:
            row["note"] = "no run.json (gap)"
            rows.append(row)
            continue
        steps = {s["name"]: s for s in run["steps"]}
        minutes = lambda s: round((ts(s["end"]) - ts(s["start"])).total_seconds() / 60, 1)
        h, sp = steps.get("hadoop-pipeline"), steps.get("spark-pipeline")
        row.update({"commit": run["commit"][:7], "shufflePartitions": run["configuration"]["shufflePartitions"],
                    "instances": f"{run['configuration']['primary']}+{run['configuration']['core']} {run['configuration']['instanceType']}",
                    "finalState": run["finalState"], "stateChangeReason": run["stateChangeReason"],
                    "hadoopState": h["state"] if h else "", "hadoopMinutes": minutes(h) if h else "",
                    "sparkState": sp["state"] if sp else "", "sparkMinutes": minutes(sp) if sp else "",
                    "normalizedInstanceHours": run["normalizedInstanceHours"],
                    "hadoopRun": run["outputs"]["hadoopRuns"][0].rsplit("run=", 1)[1] if run["outputs"]["hadoopRuns"] else ""})
        if tr:
            row.update({"clusterMinutes": tr["clusterMin"], "j01AcceptedWorks": tr["J01"], "sparkFailure": tr["sparkFailure"]})
            row["acceptedWorksPerHadoopMinute"] = round(int(tr["J01"]) / row["hadoopMinutes"]) if h and tr["J01"].isdigit() else ""
            if h and tr["hadoopMin"] and abs(float(tr["hadoopMin"]) - row["hadoopMinutes"]) > 0.1:
                t.gaps.append(f"{rec}: hadoop minutes differ: run.json {row['hadoopMinutes']}, TSV {tr['hadoopMin']}")
        else:
            t.gaps.append(f"{rec}: no complete row in {TSV} (cluster minutes, J01, Spark failure not shown)")
        rows.append(row)
    cols = ["record", "fraction", "commit", "shufflePartitions", "instances", "finalState", "stateChangeReason", "hadoopState",
            "hadoopMinutes", "j01AcceptedWorks", "acceptedWorksPerHadoopMinute", "sparkState", "sparkMinutes", "sparkFailure",
            "clusterMinutes", "normalizedInstanceHours", "hadoopRun", "note"]
    t.add("size-scaling.csv", cols, rows, "Every fraction record (failed runs included)")
    same = [r for r in rows if r.get("commit") == "deef295" and r.get("shufflePartitions") == 40]
    t.add("size-scaling-deef295.csv", cols, same, "The runs at deef295 with 40 shuffle partitions (one code version and configuration)")
    t.notes += ["Minutes are step end minus start from run.json. j01AcceptedWorks, clusterMinutes and sparkFailure come from the "
                "window 1 TSV. acceptedWorksPerHadoopMinute = j01AcceptedWorks / hadoopMinutes. The Spark step failed at 50 and 100 "
                "percent (OOM in TemporalSummaryExportJob per the TSV), so only the Hadoop step scales across all three sizes."]
    gaps = t.write()
    a = Table(root, "exp-a", "Experiment A (25 percent EMR run at deef295, Phase 14 ruling 21)")
    found = rel_glob("experiments/results/exp-a*")
    if not found:
        a.gaps.append("no raw results under experiments/results/exp-a*; experiment A's run is the deef295 25 percent pipeline "
                      "record in size-scaling (operations/pipeline-runs/20261117T045335Z-fraction25), not an experiments/results run")
    else:
        a.gaps.append(f"raw results found ({found}) but this script has no table for their format yet")
    return gaps + a.write()


# ---- Experiment D (window 2) ----

def level_rows(run, summary):
    out = []
    for lv in summary.get("levels", []):
        la = lv["latencyMsAll"]
        out.append({"run": run, "concurrency": lv["concurrency"], "startedAt": lv["startedAt"], "seconds": lv["seconds"],
                    "requests": lv["requests"], "throughputPerSecond": lv["throughputPerSecond"], "errors": lv["errors"],
                    "errorRate": lv["errorRate"], "p50Ms": la["p50"], "p95Ms": la["p95"], "p99Ms": la["p99"],
                    "desiredBefore": lv["ecsBefore"]["desired"], "desiredAfter": lv["ecsAfter"]["desired"],
                    "runningAfter": lv["ecsAfter"]["running"], "requestCapReached": lv["requestCapReached"],
                    "stoppedByAbortRule": lv["stoppedByAbortRule"]})
    return out


def run_row(t, base):
    rec = t.read(f"{base}/run-record.json", json.loads)
    summ = t.read(f"{base}/raw/summary.json", json.loads)
    row = {"run": os.path.basename(base)}
    if rec:
        row.update({"commit": rec["commit"][:7], "startedAt": rec["startedAt"], "endedAt": rec["endedAt"],
                    "exitCode": rec["exitCode"], "timedOut": rec["timedOut"]})
    if summ:
        row.update({"levels": len(summ.get("levels", [])), "aborted": summ.get("aborted") or "",
                    "preflightNon2xx": (summ.get("preflight") or {}).get("non2xx", "")})
    return row, summ


def exp_d(root):
    t = Table(root, "exp-d", "Experiment D: query load on graph-evidence-api (window 2, exp-d-query-load-v1)")
    runs, levels, kinds = [], [], []
    for base in rel_glob("experiments/results/exp-d-query-load-v1/*"):
        row, summ = run_row(t, base)
        runs.append(row)
        if summ:
            levels += level_rows(row["run"], summ)
            for lv in summ.get("levels", []):
                for k, v in sorted(lv["byKind"].items()):
                    kinds.append({"run": row["run"], "concurrency": lv["concurrency"], "kind": k, "requests": v["requests"],
                                  "errors": v["errors"], "p50Ms": v["latencyMsAll"]["p50"], "p95Ms": v["latencyMsAll"]["p95"],
                                  "p99Ms": v["latencyMsAll"]["p99"]})
    if not runs:
        t.gaps.append("no runs under experiments/results/exp-d-query-load-v1/")
    t.add("runs.csv", ["run", "commit", "startedAt", "endedAt", "exitCode", "timedOut", "levels", "preflightNon2xx", "aborted"], runs,
          "Runs (the failed preflight run included)")
    t.add("levels.csv", list(levels[0]) if levels else ["run"], levels, "Per concurrency level")
    t.add("levels-by-kind.csv", ["run", "concurrency", "kind", "requests", "errors", "p50Ms", "p95Ms", "p99Ms"], kinds,
          "Per level and request kind")
    return t.write()


# ---- Experiment D-scale (window 3) ----

def exp_d_scale(root):
    t = Table(root, "exp-d-scale", "Experiment D-scale: one concurrency-8 level and scaling of graph-evidence-api (window 3, exp-d-scale-v1)")
    row, summ = run_row(t, D_SCALE)
    t.add("runs.csv", ["run", "commit", "startedAt", "endedAt", "exitCode", "timedOut", "levels", "preflightNon2xx", "aborted"], [row], "Run")
    levels = level_rows(row["run"], summ) if summ else []
    t.add("levels.csv", list(levels[0]) if levels else ["run"], levels, "Level")
    raw = f"{D_SCALE}/raw"
    coll = t.read(f"{raw}/collect.json", json.loads) or {}
    lo = ts(coll["metricsStartUtc"]) if coll.get("metricsStartUtc") else None
    hi = ts(coll["metricsEndUtc"]) if coll.get("metricsEndUtc") else None
    within = lambda d: lo is None or hi is None or lo <= d <= hi
    ev = []
    if summ:
        ev.append((ts(summ["startedAt"]), "harness", "harness start"))
        for lv in summ.get("levels", []):
            ev += [(ts(lv["startedAt"]), "harness", f"level c{lv['concurrency']} start"),
                   (ts(lv["endedAt"]), "harness", f"level c{lv['concurrency']} end (post-observation starts)")]
        ev.append((ts(summ["endedAt"]), "harness", "post-observation end"))
    tl = t.read(f"{raw}/ecs-timeline.csv", lambda s: list(csv.DictReader(s.splitlines())))
    prev = None
    for r in tl or []:
        cur = (r["desired"], r["running"], r["pending"], r["error"])
        if cur != prev:
            ev.append((ts(r["utc"]), "ecs-timeline (30 s poll)", f"desired {r['desired']} running {r['running']} pending {r['pending']}"
                       + (f" error {r['error']}" if r["error"] else "")))
            prev = cur
    acts = t.read(f"{raw}/collect-scaling-activities.json", json.loads)
    for a in ((acts or {}).get("data") or {}).get("ScalingActivities", []):
        ev.append((ts(a["StartTime"]), "scaling-activity start", f"{a['Description']} ({a['StatusCode']})"))
        if a.get("EndTime"):
            ev.append((ts(a["EndTime"]), "scaling-activity end", a["Description"]))
    svc = t.read(f"{raw}/collect-ecs-service.json", json.loads)
    reg_times = []
    for e in ((svc or {}).get("data") or {}).get("events", []):
        d = ts(e["createdAt"])
        if within(d):
            msg = re.sub(r"\(target-group arn:[^)]*\)", "(graph-evidence-api target group)", e["message"])
            ev.append((d, "ecs-event", msg))
            if "registered 1 targets" in e["message"]:
                reg_times.append(d)
    for f in rel_glob(f"{raw}/collect-alarm-history-*.json"):
        h = t.read(f, json.loads)
        for it in ((h or {}).get("data") or {}).get("AlarmHistoryItems", []):
            d = ts(it["Timestamp"])
            if within(d) and it.get("HistoryItemType") == "StateUpdate":
                side = "AlarmHigh" if "AlarmHigh" in it["AlarmName"] else "AlarmLow" if "AlarmLow" in it["AlarmName"] else it["AlarmName"]
                ev.append((d, "alarm", f"{side}: {it['HistorySummary']}"))
    ev.sort(key=lambda x: (x[0], x[1], x[2]))
    t.add("scaling-timeline.csv", ["utc", "source", "event"], [{"utc": iso(d), "source": s, "event": m} for d, s, m in ev],
          "Scaling timeline (ECS events and alarm changes limited to the collection's metrics interval)")
    met = t.read(f"{raw}/collect-metrics.json", json.loads)
    series = {r["Id"]: dict(zip(r["Timestamps"], r["Values"])) for r in ((met or {}).get("data") or {}).get("MetricDataResults", [])}
    per_min = {i: {ts(k): v for k, v in s.items()} for i, s in series.items()}
    # Intervals and the before/after split at the second target's registration.
    intervals = []
    if summ and summ.get("levels"):
        lv = summ["levels"][0]
        l0, l1 = ts(lv["startedAt"]), ts(lv["endedAt"])
        outs = [(ts(a["StartTime"]), a) for a in ((acts or {}).get("data") or {}).get("ScalingActivities", [])]
        so = [d for d, a in outs if "desired count to 2" in a["Description"] and l0 <= d]
        si = [d for d, a in outs if "desired count to 1" in a["Description"] and d >= l1]
        reg = [d for d in reg_times if l0 <= d <= l1]
        add = lambda name, a, b: intervals.append({"interval": name, "from": iso(a), "to": iso(b), "seconds": round((b - a).total_seconds(), 1)})
        if so:
            add("level start to scale-out activity start", l0, min(so))
        else:
            t.gaps.append("no scale-out activity after the level start")
        if reg:
            add("level start to second target registered", l0, min(reg))
        else:
            t.gaps.append("no 'registered 1 targets' event during the level")
        if si:
            add("level end to scale-in activity start", l1, min(si))
        else:
            t.gaps.append("no scale-in activity after the level end")
        reqs = t.read(f"{raw}/requests-c8.csv", lambda s: list(csv.DictReader(s.splitlines())))
        phase_cols = ["phase", "from", "to", "seconds", "requests", "requestsPerSecond", "non2xx", "p50Ms", "p95Ms", "p99Ms"]

        def window(name, a, b):
            part = [r for r in reqs if a <= ts(r["startUtc"]) < b]
            lat = [float(r["latencyMs"]) for r in part]
            secs = (b - a).total_seconds()
            return {"phase": name, "from": iso(a), "to": iso(b), "seconds": round(secs, 1), "requests": len(part),
                    "requestsPerSecond": round(len(part) / secs, 2) if secs else "",
                    "non2xx": sum(1 for r in part if not r["status"].startswith("2")),
                    "p50Ms": pct(lat, 50), "p95Ms": pct(lat, 95), "p99Ms": pct(lat, 99)}

        def cpu_range(a, b):  # Neptune CPU 1-minute datapoints whose minute lies in [a, b)
            v = [x for d, x in per_min.get("neptune_cpu", {}).items() if a <= d and d + timedelta(minutes=1) <= b]
            return {"neptuneCpuMin": round(min(v), 3), "neptuneCpuMax": round(max(v), 3)} if v else {}

        phases, steady = [], []
        if reqs and reg:
            cut = min(reg)
            phases = [window("one task (level start to second target registered)", l0, cut),
                      window("two tasks registered (to level end)", cut, l1)]
            # Steady state: whole clock minutes only, away from the level start and the registration minute.
            last1 = minute_floor(cut) - timedelta(minutes=1)
            two_a, two_b = minute_floor(cut) + timedelta(minutes=1), minute_floor(l1)
            if last1 >= l0 and two_b > two_a:
                steady = [{**window("steady state: last full one-task minute", last1, last1 + timedelta(minutes=1)), **cpu_range(last1, last1 + timedelta(minutes=1))},
                          {**window("steady state: full two-task minutes", two_a, two_b), **cpu_range(two_a, two_b)}]
            else:
                t.gaps.append("no full one-task minute or no full two-task minute for the steady-state comparison")
        t.add("throughput-by-task-count.csv", phase_cols, phases,
              "Throughput and latency before and after the second task's target registration (by request start time; "
              "the one-task phase includes the level's warm-up, see the caveats)")
        # Reference: window 2's c=8 level, one warmed task (a different run, Phase 15 ruling 12(e)).
        for base in rel_glob("experiments/results/exp-d-query-load-v1/*"):
            s2 = t.read(f"{base}/raw/summary.json", json.loads) or {}
            for lv2 in s2.get("levels", []):
                if lv2["concurrency"] == 8:
                    la = lv2["latencyMsAll"]
                    steady.append({"phase": f"reference: window 2 run {os.path.basename(base)}, c=8 level, one warmed task (different run)",
                                   "from": lv2["startedAt"], "to": lv2["endedAt"], "seconds": lv2["seconds"], "requests": lv2["requests"],
                                   "requestsPerSecond": lv2["throughputPerSecond"], "non2xx": lv2["errors"],
                                   "p50Ms": la["p50"], "p95Ms": la["p95"], "p99Ms": la["p99"]})
        if not any(r["phase"].startswith("reference:") for r in steady):
            t.gaps.append("no window 2 concurrency-8 level for the reference row")
        t.add("throughput-steady-state.csv", phase_cols + ["neptuneCpuMin", "neptuneCpuMax"], steady,
              "Steady-state comparison (labelled as such): the last full one-task minute against the full two-task minutes, "
              "by request start time, with the Neptune CPU 1-minute range of the same minutes; plus window 2's c=8 level for reference")
        # Caveats (code review 3 E-m4, Phase 15 ruling 12(e)), from the same sources.
        lvl_min = sorted(d for d in per_min.get("alb_requests", {}) if minute_floor(l0) <= d < l1)
        alb = ", ".join(f"{d.strftime('%H:%M')} {per_min['alb_requests'][d]:.0f}" for d in lvl_min)
        cpu_all = [per_min.get("neptune_cpu", {}).get(d) for d in lvl_min[1:] if d + timedelta(minutes=1) <= l1]
        cpu_all = [x for x in cpu_all if x is not None]
        w2 = next((r for r in steady if r["phase"].startswith("reference:")), None)
        t.notes += ["Caveats (code review 3, E-m4; Phase 15 ruling 12(e)):", ""]
        if reg:
            t.notes += [f"- The one-task phase includes the level's warm-up. ALB requests per minute (UTC minute, count) during the level: "
                        f"{alb}; the second target registered at {iso(min(reg))}. The rise began before the second task, so the "
                        "phase averages in throughput-by-task-count.csv overstate the gain from the second task; compare the "
                        "steady-state rows instead."]
        if w2:
            t.notes += [f"- A warmed single task at concurrency 8 already served {w2['requestsPerSecond']} requests per second in window 2 "
                        f"(the reference row of throughput-steady-state.csv, level start {w2['from']})."]
        if cpu_all:
            t.notes += [f"- Neptune CPU (1-minute average) was {min(cpu_all):.1f} to {max(cpu_all):.1f} percent in every full level minute "
                        "after the first, in both phases: Neptune stayed saturated with one task and with two."]
        t.notes += ["- The split uses the ECS 'registered 1 targets' event. Registration is not health: the ALB routes to the new "
                    "target only after it passes health checks, which the events do not time (alb_healthy_* in "
                    "metrics-per-minute.csv are 1-minute samples)."]
    t.add("intervals.csv", ["interval", "from", "to", "seconds"], intervals, "Scaling intervals")
    ids = sorted(series)
    minutes = sorted({k for s in series.values() for k in s}, key=ts)
    mrows = [{"utc": iso(ts(m)), **{i: round(series[i][m], 3) if m in series[i] else "" for i in ids}} for m in minutes]
    for i in ids:
        if not series[i]:
            t.gaps.append(f"metric {i}: no datapoints in the interval")
    t.add("metrics-per-minute.csv", ["utc"] + ids, mrows, "CloudWatch 1-minute metrics (an empty cell is a missing datapoint, not zero)")
    t.notes[:0] = ["Expected finding (manifest exp-d-scale-v1): one scale-out and one scale-in at the 15 percent CPU target, and no "
                   "throughput gain from the second task while Neptune is the bottleneck. Compare the steady-state rows of "
                   "throughput-steady-state.csv (not only the phase averages in throughput-by-task-count.csv) and neptune_cpu in "
                   "metrics-per-minute.csv, with the caveats below. The CPU target of 15 percent is an experiment setting "
                   "(Phase 15 ruling 2), not a production value.", ""]
    return t.write()


# ---- Experiment F (window 2) ----

def exp_f(root):
    t = Table(root, "exp-f", "Experiment F: poison message and idempotent async replay (window 2, exp-f-failure-recovery-v1)")
    runs, checks, depths = [], [], []
    for base in rel_glob("experiments/results/exp-f-failure-recovery-v1/*"):
        rec = t.read(f"{base}/run-record.json", json.loads)
        s = t.read(f"{base}/raw/summary.json", json.loads)
        run = os.path.basename(base)
        row = {"run": run}
        if rec:
            row.update({"commit": rec["commit"][:7], "startedAt": rec["startedAt"], "endedAt": rec["endedAt"], "exitCode": rec["exitCode"]})
        if s:
            row.update({"result": s["result"], "poisonSentAt": s.get("poisonSentAt", ""), "dlqObservedAt": s.get("dlqObservedAt", ""),
                        "poisonReceiveCounts": " ".join(map(str, s.get("poisonReceiveCounts", [])))})
            if s.get("poisonSentAt") and s.get("dlqObservedAt"):
                row["sendToDlqSeconds"] = int((ts(s["dlqObservedAt"]) - ts(s["poisonSentAt"])).total_seconds())
            checks += [{"run": run, **c} for c in s.get("checks", [])]
        runs.append(row)
        qd = t.read(f"{base}/raw/queue-depths.txt")
        for line in (qd or "").splitlines():
            m = re.match(r"(\S+) jobs (\S+)\s+(\S+) dlq (\S+)\s+(\S+)$", line)
            if m:
                depths.append({"run": run, "utc": m[1], "jobsVisible": m[2], "jobsNotVisible": m[3], "dlqVisible": m[4], "dlqNotVisible": m[5]})
            elif line.strip():
                t.gaps.append(f"{run}: unparsed queue-depths line: {line}")
    if not runs:
        t.gaps.append("no runs under experiments/results/exp-f-failure-recovery-v1/")
    t.add("runs.csv", ["run", "commit", "startedAt", "endedAt", "exitCode", "result", "poisonSentAt", "dlqObservedAt", "sendToDlqSeconds",
                       "poisonReceiveCounts"], runs, "Runs")
    t.add("checks.csv", ["run", "check", "result", "detail"], checks, "Checks")
    t.add("queue-depths.csv", ["run", "utc", "jobsVisible", "jobsNotVisible", "dlqVisible", "dlqNotVisible"], depths,
          "Queue depths (ApproximateNumberOfMessages visible and not visible, about every 30 s)")
    t.notes += ["sendToDlqSeconds is dlqObservedAt minus poisonSentAt; the DLQ was polled about every 30 s, so it bounds the "
                "redrive time from above by up to one poll interval."]
    return t.write()


def derive(out):
    gaps = []
    for f in (size_scaling, exp_d, exp_d_scale, exp_f):
        gaps += [f"{f.__name__}: {g}" for g in f(out)]
    index = ["# Derived tables (Phase 15 work order 4 A5)", "",
             "Regenerate: `python3 -I experiments/analysis/derive-tables.py`. Each directory's README.md names its sources and "
             "their sha256 (also sources.csv) and lists its gaps (also gaps.csv).", "",
             "| directory | content |", "|---|---|",
             "| size-scaling/ | EMR pipeline runs at 25, 50 and 100 percent (Hadoop and Spark step minutes, accepted works) |",
             "| exp-a/ | experiment A: gap report only |",
             "| exp-d/ | experiment D levels, per kind, and runs |",
             "| exp-d-scale/ | experiment D-scale level, scaling timeline, intervals, throughput by task count, steady-state comparison and caveats, metrics per minute |",
             "| exp-f/ | experiment F checks, runs, queue depths |", "", "## All gaps", ""]
    index += [f"- {g}" for g in gaps] or ["- none"]
    with open(os.path.join(out, "README.md"), "w") as f:
        f.write("\n".join(index) + "\n")
    print(f"wrote {out}; {len(gaps)} gap(s)")
    for g in gaps:
        print(f"GAP {g}")
    return gaps


def self_test():
    """Builds the tables twice into temporary directories: byte-identical, every table has sources."""
    fails = []
    with tempfile.TemporaryDirectory() as t:
        a, b = os.path.join(t, "a"), os.path.join(t, "b")
        os.makedirs(a)
        os.makedirs(b)
        derive(a)
        derive(b)
        files = sorted(os.path.relpath(p, a) for p in glob.glob(os.path.join(a, "**", "*"), recursive=True) if os.path.isfile(p))
        same = all(open(os.path.join(a, f), "rb").read() == open(os.path.join(b, f), "rb").read() for f in files)
        for name, cond in (("two builds are byte-identical", same and files),
                           ("every table directory has README.md, sources.csv and gaps.csv",
                            all(os.path.isfile(os.path.join(a, d, f)) for d in ("size-scaling", "exp-a", "exp-d", "exp-d-scale", "exp-f")
                                for f in ("README.md", "sources.csv", "gaps.csv"))),
                           ("every source row has a 64-hex sha256",
                            all(re.fullmatch(r"[0-9a-f]{64}", r["sha256"]) for d in ("size-scaling", "exp-d", "exp-d-scale", "exp-f")
                                for r in csv.DictReader(open(os.path.join(a, d, "sources.csv"))))),
                           ("experiment A is reported as a gap", "experiments/results/exp-a" in open(os.path.join(a, "exp-a", "README.md")).read())):
            print(f"    {'PASS' if cond else 'FAIL'} {name}")
            if not cond:
                fails.append(name)
        # A missing source becomes a gap, never a value.
        tb = Table(t, "probe", "probe")
        check = tb.read("experiments/results/does-not-exist/run.json", json.loads) is None and tb.gaps == ["missing source: experiments/results/does-not-exist/run.json"]
        print(f"    {'PASS' if check else 'FAIL'} a missing source is a gap")
        if not check:
            fails.append("missing source")
    print("==> " + ("FAIL self-test" if fails else "OK self-test"))
    return 1 if fails else 0


def main(argv):
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--out", default=os.path.join(REPO, "experiments", "derived"))
    p.add_argument("--self-test", action="store_true")
    a = p.parse_args(argv)
    if a.self_test:
        return self_test()
    try:
        os.makedirs(a.out, exist_ok=True)
        derive(a.out)
    except (KeyError, ValueError, TypeError) as e:
        print(f"==> FAIL a source could not be parsed: {e!r}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
